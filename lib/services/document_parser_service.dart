import 'dart:io';
import 'package:flutter/foundation.dart';
import 'package:path/path.dart' as p;
import 'package:path_provider/path_provider.dart';
import 'package:epubx/epubx.dart' as epub;
import 'package:archive/archive.dart';
import 'package:syncfusion_flutter_pdf/pdf.dart';

import 'package:foliohaven_flutter/domain/models/book.dart';
import 'package:foliohaven_flutter/domain/models/toc_item.dart';

class ParsedMetadata {
  final String title;
  final String author;
  final String format;
  final int totalPages;
  final String coverPath;
  final List<TocItem> toc;

  const ParsedMetadata({
    required this.title,
    required this.author,
    required this.format,
    required this.totalPages,
    required this.coverPath,
    required this.toc,
  });
}

class DocumentParserService {
  static final DocumentParserService instance = DocumentParserService._internal();
  DocumentParserService._internal();

  /// Copies a user-picked file to internal persistent storage and parses its metadata.
  Future<Book> importBook(String sourcePath, {String category = 'All Books'}) async {
    final sourceFile = File(sourcePath);
    if (!await sourceFile.exists()) {
      throw Exception('Source file does not exist: $sourcePath');
    }

    final appDocDir = await getApplicationDocumentsDirectory();
    final booksDir = Directory(p.join(appDocDir.path, 'FolioHaven', 'books'));
    if (!await booksDir.exists()) {
      await booksDir.create(recursive: true);
    }

    final fileName = p.basename(sourcePath);
    final timeStamp = DateTime.now().millisecondsSinceEpoch;
    final destPath = p.join(booksDir.path, '${timeStamp}_$fileName');

    // Copy file to persistent internal storage
    await sourceFile.copy(destPath);
    final fileSize = await sourceFile.length();

    // Parse metadata
    final metadata = await parseFileMetadata(destPath);

    return Book(
      id: 0, // generated by SQLite
      title: metadata.title,
      author: metadata.author,
      format: metadata.format,
      filePath: destPath,
      fileSize: fileSize,
      currentPage: 1,
      totalPages: metadata.totalPages > 0 ? metadata.totalPages : 1,
      progressPercent: 0.0,
      isFavorite: false,
      category: category,
      coverPath: metadata.coverPath,
      createdAt: DateTime.now(),
    );
  }

  Future<ParsedMetadata> parseFileMetadata(String filePath) async {
    final ext = p.extension(filePath).toLowerCase();
    final baseName = p.basenameWithoutExtension(filePath);

    switch (ext) {
      case '.epub':
        return await _parseEpub(filePath, baseName);
      case '.pdf':
        return await _parsePdf(filePath, baseName);
      case '.cbz':
        return await _parseCbz(filePath, baseName);
      case '.txt':
      case '.fb2':
      case '.mobi':
      default:
        return _parseGenericText(filePath, baseName, ext.replaceAll('.', '').toUpperCase());
    }
  }

  Future<ParsedMetadata> _parseEpub(String filePath, String fallbackTitle) async {
    try {
      final bytes = await File(filePath).readAsBytes();
      final book = await epub.EpubReader.readBook(bytes);

      final title = book.Title?.trim().isNotEmpty == true ? book.Title!.trim() : fallbackTitle;
      final author = book.AuthorList?.join(', ') ?? book.Author ?? 'Unknown Author';

      // Save cover image if exists
      String coverPath = '';
      if (book.CoverImage != null) {
        try {
          final appDocDir = await getApplicationDocumentsDirectory();
          final coversDir = Directory(p.join(appDocDir.path, 'FolioHaven', 'covers'));
          if (!await coversDir.exists()) {
            await coversDir.create(recursive: true);
          }
          final coverFile = File(p.join(coversDir.path, '${DateTime.now().millisecondsSinceEpoch}_cover.jpg'));
          // book.CoverImage is an image.Image
          final coverBytes = book.CoverImage!;
          // Write raw bytes or encoded image
          final encoded = coverBytes.getBytes();
          if (encoded.isNotEmpty) {
            await coverFile.writeAsBytes(encoded);
            coverPath = coverFile.path;
          }
        } catch (e) {
          debugPrint('Error saving EPUB cover: $e');
        }
      }

      final List<TocItem> toc = [];
      if (book.Chapters != null && book.Chapters!.isNotEmpty) {
        for (int i = 0; i < book.Chapters!.length; i++) {
          final ch = book.Chapters![i];
          toc.add(TocItem(
            title: ch.Title?.trim().isNotEmpty == true ? ch.Title!.trim() : 'Chapter ${i + 1}',
            pageIndex: i + 1,
            level: 0,
          ));
        }
      }

      final totalPages = (book.Chapters != null && book.Chapters!.isNotEmpty) 
          ? book.Chapters!.length 
          : 1;

      return ParsedMetadata(
        title: title,
        author: author,
        format: 'EPUB',
        totalPages: totalPages,
        coverPath: coverPath,
        toc: toc,
      );
    } catch (e) {
      debugPrint('Failed to parse EPUB metadata: $e');
      return ParsedMetadata(
        title: fallbackTitle,
        author: 'Unknown Author',
        format: 'EPUB',
        totalPages: 1,
        coverPath: '',
        toc: [],
      );
    }
  }

  Future<ParsedMetadata> _parsePdf(String filePath, String fallbackTitle) async {
    try {
      final bytes = await File(filePath).readAsBytes();
      final doc = PdfDocument(inputBytes: bytes);
      final pageCount = doc.pages.count;
      doc.dispose();

      return ParsedMetadata(
        title: fallbackTitle,
        author: 'PDF Document',
        format: 'PDF',
        totalPages: pageCount > 0 ? pageCount : 1,
        coverPath: '',
        toc: [],
      );
    } catch (e) {
      debugPrint('Failed to parse PDF metadata: $e');
      return ParsedMetadata(
        title: fallbackTitle,
        author: 'PDF Document',
        format: 'PDF',
        totalPages: 1,
        coverPath: '',
        toc: [],
      );
    }
  }

  Future<ParsedMetadata> _parseCbz(String filePath, String fallbackTitle) async {
    try {
      final bytes = await File(filePath).readAsBytes();
      final archive = ZipDecoder().decodeBytes(bytes);
      int imagePages = 0;
      for (final file in archive) {
        final name = file.name.toLowerCase();
        if (name.endsWith('.jpg') || name.endsWith('.jpeg') || name.endsWith('.png') || name.endsWith('.webp')) {
          imagePages++;
        }
      }

      return ParsedMetadata(
        title: fallbackTitle,
        author: 'Comic Archive',
        format: 'CBZ',
        totalPages: imagePages > 0 ? imagePages : 1,
        coverPath: '',
        toc: [],
      );
    } catch (e) {
      return ParsedMetadata(
        title: fallbackTitle,
        author: 'Comic Archive',
        format: 'CBZ',
        totalPages: 1,
        coverPath: '',
        toc: [],
      );
    }
  }

  ParsedMetadata _parseGenericText(String filePath, String fallbackTitle, String format) {
    return ParsedMetadata(
      title: fallbackTitle,
      author: 'Unknown Author',
      format: format,
      totalPages: 1,
      coverPath: '',
      toc: [],
    );
  }

  /// Extracts chapters as text/html from EPUB
  Future<List<String>> getEpubChaptersContent(String filePath) async {
    try {
      final bytes = await File(filePath).readAsBytes();
      final book = await epub.EpubReader.readBook(bytes);
      final List<String> contents = [];

      if (book.Chapters != null && book.Chapters!.isNotEmpty) {
        for (final ch in book.Chapters!) {
          contents.add(ch.HtmlContent ?? '');
        }
      }
      return contents;
    } catch (e) {
      debugPrint('Error loading EPUB chapter content: $e');
      return [];
    }
  }

  /// Reads plain text file lines
  Future<String> readTextContent(String filePath) async {
    try {
      return await File(filePath).readAsString();
    } catch (e) {
      return 'Unable to load file content: $e';
    }
  }
}
